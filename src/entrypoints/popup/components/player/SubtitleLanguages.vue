<template>
	<div class="subtitle-languages">
		<label class="form-item form-item-select">
			<span>{{ $t("player.subtitles.priority.title") }}</span>
			<select v-model="languageToAdd" @change="addLanguage" :aria-label="$t('player.subtitles.priority.add')">
				<option value="" disabled>{{ $t("player.subtitles.priority.add") }}</option>
				<template v-for="group in availableLanguageGroups" :key="group.code">
					<optgroup v-if="group.hasVariants" :label="group.label">
						<legend>{{ group.label }}</legend>
						<option
							v-for="language in group.languages"
							:key="language.code"
							:value="language.code"
							:aria-label="language.label"
						>
							<span class="option-language"
								>{{ language.name }} <span class="option-native">({{ language.nativeName }})</span></span
							>
							<span v-if="language.autoGenerated" class="option-kind">{{
								$t("player.subtitles.priority.autoGenerated")
							}}</span>
						</option>
					</optgroup>
					<template v-else>
						<option
							v-for="language in group.languages"
							:key="language.code"
							:value="language.code"
							:aria-label="language.label"
						>
							<span class="option-language"
								>{{ language.name }} <span class="option-native">({{ language.nativeName }})</span></span
							>
							<span v-if="language.autoGenerated" class="option-kind">{{
								$t("player.subtitles.priority.autoGenerated")
							}}</span>
						</option>
					</template>
				</template>
			</select>
		</label>
		<ol v-if="config['player.settings.subtitleLanguages'].length" @dragend="clearDrag">
			<li
				v-for="(code, index) in config['player.settings.subtitleLanguages']"
				:key="code"
				:class="{
					dragging: draggingCode === code,
					'drop-before': dropTarget?.code === code && !dropTarget?.after,
					'drop-after': dropTarget?.code === code && dropTarget?.after,
				}"
				@dragover="dragOver($event, code)"
				@drop.prevent="dropLanguage"
			>
				<button
					type="button"
					class="language-action drag-handle"
					draggable="true"
					:title="$t('player.subtitles.priority.drag')"
					:aria-label="$t('player.subtitles.priority.drag')"
					@dragstart="startDrag($event, code)"
					@keydown.up.prevent="moveLanguage(index, -1)"
					@keydown.down.prevent="moveLanguage(index, 1)"
				>
					⠿
				</button>
				<span class="priority">{{ index + 1 }}</span>
				<span class="language">
					{{ languageLabels[code]?.name || code }}
					<span class="native-name">({{ languageLabels[code]?.nativeName || code }})</span>
					<span v-if="languageLabels[code]?.autoGenerated" class="caption-kind">{{
						$t("player.subtitles.priority.autoGenerated")
					}}</span>
				</span>
				<button
					type="button"
					class="language-action"
					:disabled="index === 0"
					:title="$t('player.subtitles.priority.up')"
					:aria-label="$t('player.subtitles.priority.up')"
					@click="moveLanguage(index, -1)"
				>
					↑
				</button>
				<button
					type="button"
					class="language-action"
					:disabled="index === config['player.settings.subtitleLanguages'].length - 1"
					:title="$t('player.subtitles.priority.down')"
					:aria-label="$t('player.subtitles.priority.down')"
					@click="moveLanguage(index, 1)"
				>
					↓
				</button>
				<button
					type="button"
					class="language-action remove-language"
					:title="$t('player.subtitles.priority.remove')"
					:aria-label="$t('player.subtitles.priority.remove')"
					@click="
						config['player.settings.subtitleLanguages'] = config['player.settings.subtitleLanguages'].filter(
							(_: string, position: number) => position !== index,
						)
					"
				>
					×
				</button>
			</li>
		</ol>
	</div>
</template>

<script setup lang="ts">
import { computed, ref } from "vue";
import { useI18n } from "vue-i18n";
import useConfigStore from "../../util/config";
import { languages } from "../../util/languages";
import { INSIGHTS_LANGUAGES } from "../../util/insightsLanguages";

const config = useConfigStore();
const { locale, t } = useI18n();
const languageToAdd = ref("");
const draggingCode = ref("");
const dropTarget = ref<{ code: string; after: boolean } | null>(null);
const subtitleLanguages: Record<string, string> = {
	zh: "中文",
	ja: "日本語",
	...languages,
	en: "English",
	pt: "Português",
	"pt-BR": "Português (Brasil)",
};
const languageLabels = computed(() => {
	const names = new Intl.DisplayNames([locale.value], { type: "language" });
	return Object.fromEntries(
		Object.entries(subtitleLanguages).flatMap(([code, nativeName]) => {
			const name = names.of(code) || nativeName;
			return [
				[code, { code, name, nativeName, autoGenerated: false, label: `${name} (${nativeName})` }],
				[
					`${code}:asr`,
					{
						code: `${code}:asr`,
						name,
						nativeName,
						autoGenerated: true,
						label: `${name} (${nativeName}) · ${t("player.subtitles.priority.autoGenerated")}`,
					},
				],
			];
		}),
	);
});
const availableLanguageGroups = computed(() => {
	const groups = new Map<string, string[]>();
	for (const code of new Set([...INSIGHTS_LANGUAGES, ...Object.keys(subtitleLanguages)])) {
		if (!Object.hasOwn(subtitleLanguages, code)) continue;
		const base = code.split("-")[0];
		if (!groups.has(base)) groups.set(base, []);
		groups.get(base)!.push(code);
	}
	return Array.from(groups, ([code, variants]) => ({
		code,
		label: languageLabels.value[code]?.label || code,
		hasVariants: variants.some((variant) => variant !== code),
		languages: [code, ...variants.filter((variant) => variant !== code)]
			.flatMap((variant) => [languageLabels.value[variant], languageLabels.value[`${variant}:asr`]])
			.filter((language) => language && !config["player.settings.subtitleLanguages"].includes(language.code)),
	})).filter((group) => group.languages.length);
});

function startDrag(event: DragEvent, code: string) {
	if (!event.dataTransfer) return;
	draggingCode.value = code;
	event.dataTransfer.effectAllowed = "move";
	event.dataTransfer.setData("text/plain", code);
	event.dataTransfer.setDragImage((event.currentTarget as HTMLElement).closest("li")!, 30, 20);
}

function dragOver(event: DragEvent, code: string) {
	if (!draggingCode.value) return;
	event.preventDefault();
	if (event.dataTransfer) event.dataTransfer.dropEffect = "move";
	if (draggingCode.value === code) {
		dropTarget.value = null;
		return;
	}
	const bounds = (event.currentTarget as HTMLElement).getBoundingClientRect();
	dropTarget.value = { code, after: event.clientY > bounds.top + bounds.height / 2 };
}

function dropLanguage() {
	if (draggingCode.value && dropTarget.value) {
		const reordered: string[] = config["player.settings.subtitleLanguages"].filter((code: string) => code !== draggingCode.value);
		const index = reordered.indexOf(dropTarget.value.code);
		if (index !== -1 && config["player.settings.subtitleLanguages"].includes(draggingCode.value)) {
			reordered.splice(index + Number(dropTarget.value.after), 0, draggingCode.value);
			if (reordered.some((code, position) => code !== config["player.settings.subtitleLanguages"][position])) {
				config["player.settings.subtitleLanguages"] = reordered;
			}
		}
	}
	clearDrag();
}

function clearDrag() {
	draggingCode.value = "";
	dropTarget.value = null;
}

function addLanguage() {
	if (!languageToAdd.value || config["player.settings.subtitleLanguages"].includes(languageToAdd.value)) return;
	config["player.settings.subtitleLanguages"] = [...config["player.settings.subtitleLanguages"], languageToAdd.value];
	languageToAdd.value = "";
}

function moveLanguage(index: number, direction: number) {
	const reordered: string[] = [...config["player.settings.subtitleLanguages"]];
	const target = index + direction;
	if (target < 0 || target >= reordered.length) return;
	[reordered[index], reordered[target]] = [reordered[target], reordered[index]];
	config["player.settings.subtitleLanguages"] = reordered;
}
</script>

